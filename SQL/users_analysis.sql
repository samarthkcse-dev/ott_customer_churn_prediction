select count(*) from users;

-- 1.How many total customers are registered on the platform?
select count(*) as total_user from users;

-- 2. How many active and inactive users are there?
select is_active,count(*) as no_of_users
from users
group by is_active;

-- 3.What is the distribution of customers by subscription plan?
select subscription_plan,count(*) no_of_users
from users
group by subscription_plan;

-- 4.Which country has the highest number of customers?
select country,count(*) as total_user 
from users 
group by country
limit 1;

-- 5.How many users are using each primary device?
select primary_device,count(*) as total_user 
from users 
group by primary_device;

-- 6. What are the top 10 cities with the most customers?
select city,count(*) as total_user 
from users 
group by city
order by total_user desc
limit 10;

