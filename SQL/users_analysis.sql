-- 7.Calculate the total monthly revenue generated by the platform.

select count(*) as active_users,
round(sum(Monthly_Charge),2) as monthly_revenue_$
from users
where is_active="True";

-- 8.Which subscription plan generates the highest revenue? 

select subscription_plan,round(sum(Monthly_Charge),2) as revenue_$
from users
group by subscription_plan
order by revenue_$ desc;

-- 9.Find the average revenue per customer.
select round(avg(Monthly_Charge),2) as avg_revenue_per_user
from users;

-- 10. Find the number of customers who have churned.
select count(*) as churned_users
from users
where churn=1;

-- 11. Calculate the overall customer churn rate.
select round(sum(churn)/count(*)*100,2) as churn_percentage from users;

